import { chromium, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";

const baseURL = process.env.BROWSER_TEST_URL || "http://127.0.0.1:3101";
await mkdir(".runtime/screenshots", { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1050 } });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
page.setDefaultTimeout(30000);

try {
  await page.goto("/vocabulary/learn?source=new&size=2");
  await page.getByRole("button", { name: "Start learning", exact: true }).click();
  await expect(page.getByText("Word 1 of 2", { exact: true })).toBeVisible();
  await page.locator("#vocabulary-word").focus();
  await page.keyboard.press("2");
  await expect(page.getByText("Word 1 of 2", { exact: true })).toBeVisible();
  await expect(page.locator(".vocab-save-status")).toContainText("saved as learning");
  await page.getByRole("button", { name: "Continue", exact: true }).press("Enter");
  await expect(page.getByText("Word 2 of 2", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText("Word 2 of 2", { exact: true })).toBeVisible();
  await expect(page.getByText("1 of 2 words saved", { exact: true })).toBeVisible();
  await page.screenshot({ path: ".runtime/screenshots/vocabulary-learn.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("button", { name: "Know it", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false);
  await page.screenshot({ path: ".runtime/screenshots/vocabulary-active-mobile.png", fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "Know it", exact: true }).click();
  await expect(page.getByText("All words in this session are saved. Your summary is ready.", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false);
  await page.screenshot({ path: ".runtime/screenshots/vocabulary-saved-mobile.png", fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "See session summary", exact: true }).click();
  await expect(page.getByRole("heading", { name: "2 words. A little more confident." })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.getByRole("link", { name: "Test these words", exact: true }).click();
  await page.getByLabel("Test mode", { exact: true }).selectOption("BANGLA_TO_ENGLISH");
  await page.getByRole("button", { name: "Start test", exact: true }).click();
  await expect(page.getByText("Question 1 of 2", { exact: true })).toBeVisible();
  const active = await (await context.request.get("/api/vocabulary/quiz")).json();
  const history = await (await context.request.get("/api/vocabulary/history")).json();
  const firstWord = history.sessions.flatMap((session) => session.items).find((item) => item.wordId === active.attempt.questions[0].wordId).word;
  await page.getByLabel("Your answer", { exact: true }).fill(firstWord.word);
  await page.getByLabel("Your answer", { exact: true }).press("Enter");
  await expect(page.getByText("That's right.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Next question", exact: true }).click();
  await page.getByLabel("Your answer", { exact: true }).fill("not-the-right-word");
  await page.getByRole("button", { name: "Check answer", exact: true }).click();
  await expect(page.locator(".quiz-answer-feedback.wrong")).toBeVisible();
  await expect(page.locator(".result-score")).toHaveCount(0);
  await page.screenshot({ path: ".runtime/screenshots/vocabulary-final-feedback.png", fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "See results", exact: true }).press("Enter");
  await expect(page.locator(".result-score")).toHaveText("50%");
  await page.screenshot({ path: ".runtime/screenshots/vocabulary-results.png", fullPage: true, animations: "disabled" });
  await page.reload();
  await expect(page.locator(".result-score")).toHaveText("50%");
  await page.goto(`/vocabulary/quiz?attempt=${active.attempt.id}`);
  await expect(page.locator(".result-score")).toHaveText("50%");
  await page.getByRole("link", { name: "Set up another test", exact: true }).click();
  await expect(page.getByRole("button", { name: "Start test", exact: true })).toBeVisible();
  await expect(page.locator(".result-score")).toHaveCount(0);
  await page.goto(`/vocabulary?q=${encodeURIComponent(firstWord.word)}`);
  await expect(page.getByRole("heading", { name: firstWord.word, exact: true })).toBeVisible();
  const star = page.getByRole("button", { name: new RegExp(`(Save|Remove) ${firstWord.word} (to|from) favourites`) });
  if (await star.getAttribute("aria-pressed") !== "true") await star.click();
  await expect(star).toHaveAttribute("aria-pressed", "true");
  await page.reload();
  await expect(star).toHaveAttribute("aria-pressed", "true");
  await page.getByLabel("Search vocabulary", { exact: true }).fill("no_matching_word_12345");
  await expect(page.getByRole("heading", { name: "No words match these filters", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Clear filters", exact: true }).click();
  await expect(page.locator(".word-card").first()).toBeVisible();
  await page.getByLabel("Search vocabulary", { exact: true }).fill(firstWord.word);
  await expect(page.getByRole("link", { name: "Test this word", exact: true })).toBeVisible();
  await page.goto("/vocabulary/history");
  await page.locator("details.history-row").first().locator("summary").click();
  await expect(page.getByRole("link", { name: "Test these 2 words", exact: true })).toBeVisible();
  await page.getByRole("button", { name: /Quiz attempts/ }).click();
  await expect(page.getByText("50%", { exact: true }).first()).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/vocabulary?source=weak");
  await expect(page.locator(".word-card").first()).toBeVisible();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(overflow).toBe(false);
  await page.screenshot({ path: ".runtime/screenshots/vocabulary-mobile.png", fullPage: true, animations: "disabled" });
  expect(errors).toEqual([]);
  console.log(JSON.stringify({ status: "passed", checks: ["new two-card session", "keyboard rating with visible save feedback", "explicit continue and completion", "reload resumes saved card", "typed quiz correct/wrong", "last-answer feedback before results", "results persist", "new-test setup resets correctly", "search and clear filters", "test respects visible filtered words", "favourites persist", "history", "mobile no overflow", "no page errors"] }, null, 2));
} catch (error) {
  await page.screenshot({ path: ".runtime/screenshots/vocabulary-test-failure.png", fullPage: true, animations: "disabled" });
  throw error;
} finally {
  await browser.close();
}
